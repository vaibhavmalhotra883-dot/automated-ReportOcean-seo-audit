import requests
from bs4 import BeautifulSoup
import pandas as pd
from concurrent.futures import ThreadPoolExecutor, as_completed
from google.colab import files
import time

# 1. Main Sitemap URL
MAIN_SITEMAP = "https://www.reportocean.co.jp/sitemap.xml"

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
}

def get_all_urls_from_sitemap(sitemap_url):
    print("Sitemaps fetch kiye ja rahe hain...")
    all_page_urls = []
    try:
        resp = requests.get(sitemap_url, headers=HEADERS, timeout=15)
        soup = BeautifulSoup(resp.content, "xml")

        # Sub-sitemaps nikalna
        sub_sitemaps = [loc.text.strip() for loc in soup.find_all("loc")]
        print(f"Total {len(sub_sitemaps)} sub-sitemaps mile hain. Ab inke andar ke URLs nikal rahe hain...")

        for sub in sub_sitemaps:
            try:
                sub_resp = requests.get(sub, headers=HEADERS, timeout=15)
                sub_soup = BeautifulSoup(sub_resp.content, "xml")
                urls = [loc.text.strip() for loc in sub_soup.find_all("loc")]
                all_page_urls.extend(urls)
                print(f" -> {sub.split('/')[-1]} se {len(urls)} URLs mile.")
            except Exception as e:
                print(f"Error reading {sub}: {e}")

    except Exception as e:
        print(f"Main sitemap error: {e}")

    # Duplicate URLs hatana
    return list(dict.fromkeys(all_page_urls))

def audit_url(url):
    title_text = ""
    title_len = 0
    error_msg = "No Error"
    impact = "Low"
    priority = "P3 - Low"

    try:
        response = requests.get(url, headers=HEADERS, timeout=15)
        status = response.status_code

        if status != 200:
            error_msg = f"HTTP Status {status}"
            impact = "High - Page Not Accessible / Indexing Drop"
            priority = "P1 - High"
        else:
            soup = BeautifulSoup(response.text, "html.parser")
            title_tag = soup.find("title")

            if title_tag and title_tag.text.strip():
                title_text = title_tag.text.strip()
                title_len = len(title_text)

                # Japanese / English SEO Title Length Check
                if title_len < 15:
                    error_msg = "Title Too Short"
                    impact = "High - Poor CTR & Weak Keyword Relevance"
                    priority = "P1 - High"
                elif title_len > 65:
                    error_msg = "Title Too Long (Truncation Risk)"
                    impact = "Medium - Title Cuts Off in Google SERP"
                    priority = "P2 - Medium"
                else:
                    error_msg = "OK"
                    impact = "Optimal - Good for Search Visibility"
                    priority = "P3 - Low"
            else:
                error_msg = "Missing Title Tag"
                impact = "Critical - Severe Ranking & CTR Loss"
                priority = "P1 - High"

    except requests.exceptions.Timeout:
        error_msg = "Request Timeout"
        impact = "High - Slow Server / Crawl Budget Waste"
        priority = "P1 - High"
    except Exception as e:
        error_msg = f"Connection Error: {str(e)[:40]}"
        impact = "High - Crawl Failure"
        priority = "P1 - High"

    return {
        "Urls": url,
        "Title": title_text,
        "Title Length": title_len,
        "Error": error_msg,
        "Business Impact": impact,
        "Priority": priority
    }

# --- Execution Start ---
start_time = time.time()
urls_to_crawl = get_all_urls_from_sitemap(MAIN_SITEMAP)
total_urls = len(urls_to_crawl)
print(f"\nTotal {total_urls} unique URLs crawl karne ke liye taiyar hain. Audit shuru ho raha hai...\n")

results = []
# max_workers=15 rakha hai taaki server block na kare aur kaam 2-3 minute mein ho jaye
with ThreadPoolExecutor(max_workers=15) as executor:
    future_to_url = {executor.submit(audit_url, url): url for url in urls_to_crawl}

    for count, future in enumerate(as_completed(future_to_url), 1):
        results.append(future.result())
        if count % 100 == 0 or count == total_urls:
            print(f"Progress: {count}/{total_urls} URLs complete...")

# DataFrame banana aur Duplicate Titles check karna
df = pd.DataFrame(results)

# Duplicate Title check (agar koi title 1 se zyada baar aaya hai)
duplicate_titles = df[df.duplicated(subset=['Title'], keep=False) & (df['Title'] != "")]
for idx in duplicate_titles.index:
    if df.loc[idx, 'Error'] == "OK":
        df.loc[idx, 'Error'] = "Duplicate Title"
        df.loc[idx, 'Business Impact'] = "Medium - Keyword Cannibalization Risk"
        df.loc[idx, 'Priority'] = "P2 - Medium"

# Excel File Save aur Auto-Download
file_name = "ReportOcean_SEO_Title_Audit.xlsx"
df.to_excel(file_name, index=False)

print(f"\nAudit poora hua! Total time: {round(time.time() - start_time, 2)} seconds.")
print("Excel file download ho rahi hai...")
files.download(file_name)